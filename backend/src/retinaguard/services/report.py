# ---------------------------------------------------------------------------
# Report builder
# ---------------------------------------------------------------------------


class ReportService:
    """Generates structured, bilingual, PHI-free screening reports."""

    @staticmethod
    def build_text_report(result: ScreeningResult, lang: str = "en") -> str:
        """Render a plain-text clinical summary.

        Args:
            result: Completed ScreeningResult from the screen endpoint.
            lang: "en" for English, "hi" for Hindi.

        Returns:
            Multi-line plain-text report string.
        """
        is_en = lang != "hi"
        grade_val = int(result.grade) if result.grade is not None else -1

        grade_label = (
            (_GRADE_LABEL_EN if is_en else _GRADE_LABEL_HI).get(grade_val, "Unknown")
        )
        referral_text = (_REFERRAL_TEXT_EN if is_en else _REFERRAL_TEXT_HI)[result.referral]
        urgency_text = (_URGENCY_TEXT_EN if is_en else _URGENCY_TEXT_HI)[result.urgency]
        disclaimer = _DISCLAIMER_EN if is_en else _DISCLAIMER_HI

        if is_en:
            lines = [
                "=" * 60,
                "  RetinaGuard Diabetic Retinopathy Screening Report",
                "  *** PROTOTYPE ONLY - NOT CLINICALLY VALIDATED ***",
                "=" * 60,
                f"Screening ID     : {result.screening_id}",
                f"Date / Time (UTC): {result.created_at.strftime('%Y-%m-%d %H:%M:%S')}",
                f"Patient ID       : {result.patient_pseudonym_id}",
                f"Eye              : {result.eye_side}",
                f"Camera           : {result.camera_type}",
                "-" * 60,
                "FINDINGS",
                f"  DR Grade       : {grade_label}",
                f"  Confidence     : {f'{result.confidence:.1%}' if result.confidence is not None else 'N/A'}",
                f"  Referral       : {referral_text}",
                f"  Urgency        : {urgency_text}",
                f"  Follow-up in   : {result.follow_up_interval_months} month(s)",
            ]
            if result.is_uncertain:
                lines.append(f"  ⚠ Uncertain    : {'; '.join(result.uncertainty_reasons)}")
            lines += [
                "-" * 60,
                "GUIDELINES",
                "  " + ", ".join(result.guideline_sources),
                "-" * 60,
                "DISCLAIMER",
                disclaimer,
                "=" * 60,
            ]
        else:
            lines = [
                "=" * 60,
                "  RetinaGuard मधुमेह रेटिनोपैथी जांच रिपोर्ट",
                "  *** प्रोटोटाइप - चिकित्सकीय रूप से प्रमाणित नहीं ***",
                "=" * 60,
                f"स्क्रीनिंग ID    : {result.screening_id}",
                f"दिनांक/समय (UTC) : {result.created_at.strftime('%Y-%m-%d %H:%M:%S')}",
                f"रोगी ID          : {result.patient_pseudonym_id}",
                f"आंख              : {result.eye_side}",
                f"कैमरा            : {result.camera_type}",
                "-" * 60,
                "निष्कर्ष",
                f"  DR ग्रेड        : {grade_label}",
                f"  विश्वास स्तर    : {f'{result.confidence:.1%}' if result.confidence is not None else 'उपलब्ध नहीं'}",
                f"  रेफरल          : {referral_text}",
                f"  तात्कालिकता    : {urgency_text}",
                f"  अनुवर्ती अवधि  : {result.follow_up_interval_months} महीने",
            ]
            if result.is_uncertain:
                lines.append(f"  ⚠ अनिश्चित     : {'; '.join(result.uncertainty_reasons)}")
            lines += [
                "-" * 60,
                "दिशानिर्देश",
                "  " + ", ".join(result.guideline_sources),
                "-" * 60,
                "अस्वीकरण",
                disclaimer,
                "=" * 60,
            ]

        return "\n".join(lines)

    @staticmethod
    def build_json_report(result: ScreeningResult) -> dict[str, Any]:
        """Serialise a ScreeningResult to a structured API-safe dict."""
        grade_val = int(result.grade) if result.grade is not None else None
        return {
            "screening_id": str(result.screening_id),
            "created_at": result.created_at.isoformat(),
            "patient_pseudonym_id": result.patient_pseudonym_id,
            "eye_side": result.eye_side,
            "camera_type": result.camera_type,
            "grade": grade_val,
            "grade_label_en": _GRADE_LABEL_EN.get(grade_val, "Unknown") if grade_val is not None else None,
            "grade_label_hi": _GRADE_LABEL_HI.get(grade_val, "अज्ञात") if grade_val is not None else None,
            "confidence": result.confidence,
            "referral": result.referral,
            "urgency": result.urgency,
            "follow_up_interval_months": result.follow_up_interval_months,
            "is_uncertain": result.is_uncertain,
            "uncertainty_reasons": result.uncertainty_reasons,
            "clinician_review_mandatory": True,
            "report_en": result.report_en,
            "report_hi": result.report_hi,
            "image_sha256": result.image_sha256,
            "audit_hash": result.audit_hash,
            "previous_audit_hash": result.previous_audit_hash,
            "guideline_sources": result.guideline_sources,
            "disclaimer_en": _DISCLAIMER_EN,
            "disclaimer_hi": _DISCLAIMER_HI,
        }

